let current: Lang = "fr";
try {
  const saved = window.localStorage?.getItem("pssst.lang");
  if (saved === "fr" || saved === "en") current = saved;
} catch {
  /* storage unavailable in test/preview */
}

const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  try {
    window.localStorage?.setItem("pssst.lang", lang);
  } catch {
    /* storage unavailable in test/preview */
  }
  listeners.forEach((listener) => listener());
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (notify) => {
      listeners.add(notify);
      return () => listeners.delete(notify);
    },
    () => current,
  );
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let out: string = (current === "en" ? en : fr)[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.split(`{${name}}`).join(String(value));
    }
  }
  return out;
}

/** Subscribes the component to language changes and returns `t`. */
export function useT(): typeof t {
  useLang();
  return t;
}
